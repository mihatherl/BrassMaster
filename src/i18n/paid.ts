/**
 * The strings that belong to the paid features, kept where the free build can
 * drop them.
 *
 * ## Why these live apart
 *
 * The free/paid line is drawn at build time so that the free bundle *does not
 * hold* what it does not offer — `check-web-bundle.mjs` exists to prove it,
 * and the note at the top of that file records the two occasions the property
 * was broken silently. The language packs were quietly on the wrong side of
 * that line: they are plain objects imported unconditionally, so every
 * sentence of My Music and the course screens shipped to the free web build,
 * in every language, for features it has no code for. Eight languages turned
 * a small leak into a visible one — the free bundle described a product it
 * could not run.
 *
 * Ruled by the player, 2026-08-28, in the same breath as the two Portuguese
 * packs: split the build targets.
 *
 * ## How the dropping works
 *
 * Two buckets, not one, each read through its own literal in `index.ts` —
 * `__HAS_MY_MUSIC__` and `__HAS_TEACHER__`. `vite.config.ts` explains why a
 * single `__IS_PAID__` was refused: it would have to be unpicked at every use
 * site the day the first feature moves. The same argument applies here, so
 * there are two.
 *
 * Rollup folds `false ? PAID_… : {}` to `{}`, the export binding goes
 * unreferenced, and the module is tree-shaken away. That is the mechanism
 * that already removes `ProgressScreen` from the free build. **It is not
 * assumed**: `check:web` fingerprints a string from each bucket, so a
 * regression fails the deploy rather than shipping quietly.
 *
 * The English halves are exported separately because `StringKey` is built
 * from them: the type must name every key in both builds, or the two targets
 * would be two codebases. They are types at that use site and cost nothing.
 *
 * ## What is NOT here
 *
 * `home.myMusic` — the label on the door. `SettingsScreen` takes that door as
 * an optional callback rather than reading the flag itself, deliberately, so
 * both sides of the line are testable in one run (see `target.test.tsx`). The
 * label is reachable in the free build's source whatever the flag says, and
 * moving it here would only make `t()` return a bare key on the free build's
 * own home screen. One string is the honest price of that testability.
 */

